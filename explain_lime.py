"""
explain_lime.py
---------------
Model Interpretability Module using LIME (Local Interpretable Model-agnostic Explanations).

Capabilities:
- `EmailClassifierExplainer` class:
  + Agnostic interface supporting both 'naive_bayes' (scikit-learn pipeline) and 'distilbert' (PyTorch Transformer).
  + Batched inference with torch.no_grad() optimization for GPU/CPU memory efficiency.
  + Feature importance extraction: ranks top contributing token weights toward Ham/Spam decisions.
  + Generates interactive self-contained HTML text highlighting for visualization panes.
- Command-line interface (CLI) for rapid single-instance explanation testing.
"""

import os
import re
import argparse
import joblib
import numpy as np
import torch
from lime.lime_text import LimeTextExplainer
from transformers import AutoTokenizer, AutoModelForSequenceClassification

NB_MODEL_PATH = "models/naive_bayes.joblib"
DISTILBERT_DIR = "models/distilbert"

class EmailClassifierExplainer:
    """Interpretable explanation wrapper applying LIME to text classification models."""
    def __init__(self, model_type="distilbert"):
        self.model_type = model_type.lower()
        self.class_names = ["Ham", "Spam"]
        self.explainer = LimeTextExplainer(class_names=self.class_names, random_state=42)
        
        self.nb_pipeline = None
        self.bert_model = None
        self.bert_tokenizer = None
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        self._load_model()

    def _load_model(self):
        if self.model_type == "naive_bayes":
            if not os.path.exists(NB_MODEL_PATH):
                raise FileNotFoundError(
                    f"Naive Bayes model artifact missing at: {NB_MODEL_PATH}. "
                    "Please execute 'python train_nb.py' first!"
                )
            self.nb_pipeline = joblib.load(NB_MODEL_PATH)
        elif self.model_type == "distilbert":
            if not os.path.exists(DISTILBERT_DIR):
                raise FileNotFoundError(
                    f"DistilBERT model artifacts missing at: {DISTILBERT_DIR}. "
                    "Please execute 'python train_distilbert.py' first!"
                )
            self.bert_tokenizer = AutoTokenizer.from_pretrained(DISTILBERT_DIR)
            self.bert_model = AutoModelForSequenceClassification.from_pretrained(DISTILBERT_DIR)
            self.bert_model.to(self.device)
            self.bert_model.eval()
        else:
            raise ValueError(f"Unsupported model type: {self.model_type}. Choose 'naive_bayes' or 'distilbert'.")

    def _predict_proba_bert(self, texts, batch_size=16, max_length=256):
        """Memory-bounded softmax probability inference for LIME perturbation batches."""
        all_probs = []
        for i in range(0, len(texts), batch_size):
            batch_texts = [str(t) for t in texts[i:i + batch_size]]
            encoding = self.bert_tokenizer(
                batch_texts,
                truncation=True,
                padding=True,
                max_length=max_length,
                return_tensors="pt"
            )
            input_ids = encoding["input_ids"].to(self.device)
            attention_mask = encoding["attention_mask"].to(self.device)

            with torch.no_grad():
                outputs = self.bert_model(input_ids=input_ids, attention_mask=attention_mask)
                probs = torch.softmax(outputs.logits, dim=-1).cpu().numpy()
                all_probs.append(probs)

        if len(all_probs) == 0:
            return np.empty((0, 2))
        return np.vstack(all_probs)

    def predict_proba(self, texts):
        """Unified prediction interface returning [P(Ham), P(Spam)] consumed by LIME."""
        if self.model_type == "naive_bayes":
            return self.nb_pipeline.predict_proba(texts)
        else:
            return self._predict_proba_bert(texts)

    def explain(self, text: str, num_features: int = 6, num_samples: int = 300) -> dict:
        """
        Explain model classification decision for a target email document.
        
        Args:
            text: Raw email text document to analyze.
            num_features: Number of top salient token features to extract (default: 6).
            num_samples: Number of perturbation samples generated by LIME (default: 300).
            
        Returns:
            Dictionary containing predicted label, class probabilities, feature weights, and HTML visual snippet.
        """
        clean_text = str(text).strip()
        if not clean_text:
            return {
                "predicted_label": "Ham",
                "probability": {"Ham": 0.5, "Spam": 0.5},
                "top_features": [],
                "html_visualization": "<p>Empty text input. No explanation can be generated.</p>"
            }

        # Baseline class inference
        initial_probs = self.predict_proba([clean_text])[0]
        pred_idx = int(np.argmax(initial_probs))
        pred_label = self.class_names[pred_idx]

        # Guard against inputs with no parseable word tokens
        words = re.findall(r"\w+", clean_text)
        if not words:
            return {
                "predicted_label": pred_label,
                "probability": {
                    "Ham": round(float(initial_probs[0]), 4),
                    "Spam": round(float(initial_probs[1]), 4)
                },
                "top_features": [],
                "html_visualization": f"<p>Document contains no alphanumeric word tokens for attribution: {clean_text}</p>"
            }

        # Generate LIME local surrogate explanation
        try:
            exp = self.explainer.explain_instance(
                text_instance=clean_text,
                classifier_fn=self.predict_proba,
                labels=[1],  # Attribute probability toward positive Spam class (index 1)
                num_features=num_features,
                num_samples=num_samples
            )

            # Extract token weights
            feature_weights = exp.as_list(label=1)
            top_features = []
            for word, weight in feature_weights:
                # Positive weight indicates evidence for Spam; negative weight indicates evidence for Ham
                target = "Spam" if weight > 0 else "Ham"
                top_features.append({
                    "word": word,
                    "weight": round(float(weight), 4),
                    "target": target
                })

            html_visualization = exp.as_html()
        except Exception as e:
            top_features = []
            html_visualization = f"<p>LIME explanation generation failed: {e}</p>"

        return {
            "predicted_label": pred_label,
            "probability": {
                "Ham": round(float(initial_probs[0]), 4),
                "Spam": round(float(initial_probs[1]), 4)
            },
            "top_features": top_features,
            "html_visualization": html_visualization
        }

def main():
    parser = argparse.ArgumentParser(description="CLI Diagnostic Tool for LIME Model Interpretability")
    parser.add_argument("--text", type=str, required=True, help="Target email text body to interpret")
    parser.add_argument("--model", type=str, default="naive_bayes", choices=["naive_bayes", "distilbert"],
                        help="Target classifier architecture: 'naive_bayes' or 'distilbert' (default: 'naive_bayes')")
    parser.add_argument("--num_features", type=int, default=6, help="Top salient features count (default: 6)")
    parser.add_argument("--num_samples", type=int, default=250, help="LIME perturbation sample count (default: 250)")
    args = parser.parse_args()

    print(f"[*] Initializing LIME Explainer module with model: {args.model}...")
    explainer = EmailClassifierExplainer(model_type=args.model)

    print(f"[*] Computing local linear surrogate explanation...")
    result = explainer.explain(args.text, num_features=args.num_features, num_samples=args.num_samples)

    print("\n" + "=" * 54)
    print("            LIME EXPLAINABILITY REPORT")
    print("=" * 54)
    print(f"Predicted Verdict:  {result['predicted_label']}")
    print(f"Posterior Proba:    Ham: {result['probability']['Ham']:.2%} | Spam: {result['probability']['Spam']:.2%}")
    print("\nSalient Attribution Tokens:")
    for item in result["top_features"]:
        sign = "+" if item["weight"] > 0 else ""
        print(f"  - {item['word']:<15} : {sign}{item['weight']:.4f}  (Supports {item['target']})")
    print("=" * 54)

if __name__ == "__main__":
    main()
